-- La migración 0049_chile_master_data.sql creó las tablas chile_regions /
-- chile_communes / chile_zones pero su seed NUNCA llegó a ejecutarse: tiene dos
-- comillas simples sin escapar que rompen el SQL,
--
--     ('VI', 'O'Higgins', 'Región del Libertador General Bernardo O'Higgins'),
--                 ^                                                  ^
--     ('Centro'), ('Estación Central'), ('Parque O'Higgins'),
--
-- En PostgreSQL eso es un error de sintaxis que aborta la sentencia entera, y
-- con ON_ERROR_STOP=1 aborta el resto del fichero. Resultado: las tres tablas
-- quedaron VACÍAS en producción desde entonces, sin que nada lo delatara.
--
-- Lo destapó la API pública: GET /api/v1/catalogos?tipo=regiones devolvía [],
-- así que un integrador externo no tenía contra qué normalizar región y comuna
-- —justo lo que la documentación le pide hacer— y acababa mandando la
-- nomenclatura de su propia base de datos.
--
-- Esta migración reescribe el seed correctamente escapado y COMPLETO: las 16
-- regiones y las 346 comunas oficiales de Chile (antes solo se intentaban ~40).
-- Es idempotente (ON CONFLICT DO NOTHING), así que se puede reejecutar.
--
-- No se toca 0049: reescribir una migración ya registrada en schema_migrations
-- no se volvería a aplicar en los VPS que la tienen marcada, y sí se aplicaría
-- dos veces en los que usan post-deploy.sh. Se corrige hacia delante.
-- ============================================================================

-- Las tablas pueden no existir si 0049 abortó antes de crearlas.
CREATE TABLE IF NOT EXISTS chile_regions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  full_name TEXT
);

CREATE TABLE IF NOT EXISTS chile_communes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  region_id UUID NOT NULL REFERENCES chile_regions(id),
  code TEXT UNIQUE,
  name TEXT NOT NULL,
  UNIQUE(region_id, name)
);

CREATE TABLE IF NOT EXISTS chile_zones (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  commune_id UUID NOT NULL REFERENCES chile_communes(id),
  name TEXT NOT NULL,
  UNIQUE(commune_id, name)
);

CREATE INDEX IF NOT EXISTS idx_chile_communes_region_id ON chile_communes(region_id);
CREATE INDEX IF NOT EXISTS idx_chile_zones_commune_id ON chile_zones(commune_id);

