-- alguna instalación llegó a insertarlo, se corrige antes de sembrar Ñuble para
-- que no choque contra el UNIQUE de `code`.
UPDATE chile_regions
   SET code = 'XIV', full_name = 'Región de Los Ríos'
 WHERE name = 'Los Ríos' AND code = 'XVI';

